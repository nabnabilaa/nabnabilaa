# ---------- fonts ----------
FONT_FILES = {
    'F': ('nmF', 'normal', '100 900', 'fraunces-normal-var-latin.woff2'),
    'FI': ('nmF', 'italic', '100 900', 'fraunces-italic-var-latin.woff2'),
    'I': ('nmI', 'normal', '100 900', 'inter-normal-var-latin.woff2'),
    'M': ('nmM', 'normal', '100 800', 'jetbrains-mono-normal-var-latin.woff2'),
}
_tt = {}


def tt(key):
    if key not in _tt:
        _tt[key] = TTFont(HERE / 'fonts' / FONT_FILES[key][3])
    return _tt[key]


# Fraunces' default instance is its black weight; at the 400 set here the
# letters are narrower, and this is how much, checked against renders.
WIDTH_FIX = {'F': .86, 'FI': .84, 'I': 1.0, 'M': 1.0}


def measure(text, key, size, ls=0.0):
    f = tt(key)
    cmap, hmtx, upm = f.getBestCmap(), f['hmtx'], f['head'].unitsPerEm
    w = 0
    for ch in text:
        g = cmap.get(ord(ch))
        w += (hmtx[g][0] if g else upm * .5) / upm * size
    return w * WIDTH_FIX[key] + ls * max(len(text) - 1, 0)


def wrap(text, key, size, width, ls=0.0, sep=' '):
    out, line = [], ''
    for word in text.split(sep):
        trial = line + sep + word if line else word
        if line and measure(trial, key, size, ls) > width:
            out.append(line)
            line = word
        else:
            line = trial
    if line:
        out.append(line)
    return out


def font_face(key, chars):
    family, style, weight, file = FONT_FILES[key]
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'calt']
    opts.name_IDs = []
    opts.notdef_outline = True
    font = TTFont(HERE / 'fonts' / file)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes={ord(c) for c in chars | {' '}})
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    b64 = base64.b64encode(buf.getvalue()).decode()
    return f"@font-face{{font-family:'{family}';font-style:{style};font-weight:{weight};src:url(data:font/woff2;base64,{b64}) format('woff2')}}"


# ---------- pictures ----------
_img = {}


def jpeg(file, width, crop=None):
    k = (file, width, crop)
    if k not in _img:
        im = Image.open(HERE / 'img' / file).convert('RGB')
        if crop:
            im = im.crop(crop)
        h = round(im.height * width / im.width)
        im = im.resize((width, h), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, 'JPEG', quality=80, optimize=True, progressive=True)
        _img[k] = 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()
    return _img[k]


# ---------- the cloth: Truntum, straight from batik.js ----------
_batik = {}


def truntum(pid, fg, scale=1.0):
    k = (fg, scale)
    if k not in _batik:
        js = ("const B=require(%s);process.stdout.write(B.svg({motif:'truntum',fg:%s,bg:'none',scale:%s}))"
              % (json.dumps(str(HERE / 'vendor' / 'batik.js')), json.dumps(fg), scale))
        svg = subprocess.run(['node', '-e', js], capture_output=True, text=True, check=True).stdout
        start, end = svg.index('<pattern'), svg.index('</pattern>') + len('</pattern>')
        _batik[k] = svg[start:end]
    return _batik[k].replace('id="p"', f'id="{pid}"', 1)


def esc(s):
    return html.escape(s, quote=True)


# ---------- one drawing ----------
class Svg:
    def __init__(self, w, h, title):
        self.w, self.h, self.title = w, h, title
        self.defs, self.parts, self.css = [], [], []
        self.used = {k: set() for k in FONT_FILES}
        self._n = 0

    def uid(self, p='u'):
        self._n += 1
        return f'{p}{self._n}'

    def add(self, s):
        self.parts.append(s)

    def run(self, s, key, fill, weight=None, size=None, ls=None, dx=None):
        self.used[key].update(s)
        fam, style = FONT_FILES[key][0], FONT_FILES[key][1]
        a = f' font-family="{fam}"'
        if style == 'italic':
            a += ' font-style="italic"'
        if weight:
            a += f' font-weight="{weight}"'
        if size:
            a += f' font-size="{size}"'
        if ls is not None:
            a += f' letter-spacing="{ls}"'
        if dx:
            a += f' dx="{dx}"'
        return f'<tspan{a} fill="{fill}">{esc(s)}</tspan>'

    def text(self, x, y, runs, size, anchor=None, ls=0, weight=None):
        """runs: [(text, fontkey, fill[, weight])]"""
        body = ''.join(self.run(r[0], r[1], r[2], r[3] if len(r) > 3 else weight) for r in runs)
        a = f' text-anchor="{anchor}"' if anchor else ''
        self.add(f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" letter-spacing="{ls}"{a}>{body}</text>')

    def t(self, x, y, s, key, size, fill, **kw):
        self.text(x, y, [(s, key, fill)], size, **kw)

    def render(self):
        faces = ''.join(font_face(k, c) for k, c in self.used.items() if c)
        css = faces + "text{font-optical-sizing:auto;font-kerning:normal}" + ''.join(self.css)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" '
                f'viewBox="0 0 {self.w} {self.h}" role="img" aria-label="{esc(self.title)}">'
                f'<title>{esc(self.title)}</title><defs><style>{css}</style>{"".join(self.defs)}</defs>'
                f'{"".join(self.parts)}</svg>')


def arrow(x, y, s, color, diagonal=False, width=1.8):
    """→ or ↗ as a path: the portfolio's fonts carry no arrow glyphs."""
    if diagonal:
        d = f'M{x:.1f} {y:.1f}L{x + s:.1f} {y - s:.1f}M{x + s * .3:.1f} {y - s:.1f}H{x + s:.1f}V{y - s * .7:.1f}'
    else:
        d = f'M{x:.1f} {y:.1f}H{x + s:.1f}M{x + s * .6:.1f} {y - s * .4:.1f}L{x + s:.1f} {y:.1f}L{x + s * .6:.1f} {y + s * .4:.1f}'
    return f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>'


def deep_panel(g, w, h, rx=22, glow=(0.14, 0.30), indigo=(0.88, 0.78), cloth=None):
    """The portfolio's ground: warm charcoal, a pink glow, an indigo one, and
    optionally the cloth fading in from one side."""
    cid, pg, ig = g.uid('c'), g.uid('g'), g.uid('g')
    g.defs.append(f'<clipPath id="{cid}"><rect width="{w}" height="{h}" rx="{rx}"/></clipPath>'
                  f'<radialGradient id="{pg}" cx="{glow[0]}" cy="{glow[1]}" r=".62"><stop offset="0" stop-color="{PINK}" stop-opacity=".17"/><stop offset="1" stop-color="{PINK}" stop-opacity="0"/></radialGradient>'
                  f'<radialGradient id="{ig}" cx="{indigo[0]}" cy="{indigo[1]}" r=".55"><stop offset="0" stop-color="rgb({INDIGO})" stop-opacity=".14"/><stop offset="1" stop-color="rgb({INDIGO})" stop-opacity="0"/></radialGradient>')
    g.add(f'<g clip-path="url(#{cid})"><rect width="{w}" height="{h}" fill="{DEEP}"/>'
          f'<rect width="{w}" height="{h}" fill="url(#{pg})"/><rect width="{w}" height="{h}" fill="url(#{ig})"/>')
    if cloth:
        side, opacity, scale = cloth
        pat, mg, mk = g.uid('p'), g.uid('g'), g.uid('m')
        x1, x2 = ('0', '1') if side == 'right' else ('1', '0')
        g.defs.append(truntum(pat, PINK, scale) +
                      f'<linearGradient id="{mg}" x1="{x1}" y1="0" x2="{x2}" y2="0"><stop offset=".35" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#fff" stop-opacity="1"/></linearGradient>'
                      f'<mask id="{mk}"><rect width="{w}" height="{h}" fill="url(#{mg})"/></mask>')
        g.add(f'<rect width="{w}" height="{h}" fill="url(#{pat})" opacity="{opacity}" mask="url(#{mk})"/>')
    return cid


def close_panel(g, w, h, rx=22):
    g.add('</g>')
    g.add(f'<rect x=".5" y=".5" width="{w - 1}" height="{h - 1}" rx="{rx - .5}" fill="none" stroke="{LINE2}"/>')


def glass(g, x, y, w, h, rx=20, strong=False):
    gid = g.uid('g')
    top = .13 if strong else .075
    g.defs.append(f'<linearGradient id="{gid}" x1="0" y1="0" x2=".55" y2="1"><stop offset="0" stop-color="#fff" stop-opacity="{top}"/>'
                  f'<stop offset=".55" stop-color="#fff" stop-opacity="{top * .4:.3f}"/><stop offset="1" stop-color="#fff" stop-opacity=".015"/></linearGradient>')
    # frosted: whatever is behind the glass is dimmed, not shown through
    g.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{DEEP}" opacity="{.82 if strong else .55}"/>')
    g.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="url(#{gid})" stroke="{GLASS_LINE2 if strong else LINE2}"/>'
          f'<path d="M{x + rx} {y + .5}H{x + w - rx}" stroke="rgba(255,255,255,.28)"/>')


def screen(g, file, x, y, w, h, rx=14, img_w=1000):
    cid, fid = g.uid('c'), g.uid('f')
    g.defs.append(f'<clipPath id="{cid}"><rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}"/></clipPath>'
                  f'<filter id="{fid}" x="-10%" y="-10%" width="120%" height="130%"><feDropShadow dx="0" dy="22" stdDeviation="24" flood-color="#000" flood-opacity=".55"/></filter>')
    g.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{DEEP3}" filter="url(#{fid})"/>'
          f'<image x="{x}" y="{y}" width="{w}" height="{h}" preserveAspectRatio="xMidYMin slice" href="{jpeg(file, img_w)}" clip-path="url(#{cid})"/>'
          f'<rect x="{x + .5}" y="{y + .5}" width="{w - 1}" height="{h - 1}" rx="{rx - .5}" fill="none" stroke="{GLASS_LINE2}"/>')


